import re

# דרישה -> (שדה ב-metadata, ערכים שעונים עליה, ביטויים שמזהים אותה בשאלה)
FEATURES = {
    "accessible": ("accessible", ["כן", "חלקית"],
                   ["נגיש", "נגישה", "נגישים", "מונגש", "מונגשת", "כיסא גלגלים", "כסא גלגלים",
                    "עגלה", "עגלות", "עגלת"]),
    "water": ("water", ["כן"],
              ["מים", "להירטב", "רטוב", "רטובים", "בריכה", "בריכות", "מעיין", "מעיינות"]),
    "circular": ("circular", ["כן", "חלקית"], ["מעגלי", "מעגלית", "מעגליים"]),
    "free": ("entry_fee", ["חינם"],
             ["חינם", "בלי לשלם", "ללא תשלום", "בלי תשלום", "לא לשלם", "לא צריך לשלם"]),
    "easy": ("difficulty", ["קל"],
             ["מסלול קל", "מסלולים קלים", "טיול קל", "הליכה קלה", "קל במיוחד"]),
}


def _pattern(phrase):
    """ביטוי כמילה שלמה, עם עד שתי אותיות תחילית (ו, ב, ל, ה, מ, ש, כ) - כדי ש'מים' לא יימצא בתוך 'מתאימים'."""
    return re.compile(rf"(?<![א-ת])[ובלהמשכ]{{0,2}}{re.escape(phrase)}(?![א-ת])")


PATTERNS = {name: [_pattern(p) for p in phrases] for name, (_, _, phrases) in FEATURES.items()}


def extract_filters(question):
    """מזהה בשאלה דרישות לפי מילות מפתח (בלי LLM) ומחזירה תנאי סינון: {שדה: ערכים מותרים}."""
    found = [name for name, pats in PATTERNS.items() if any(p.search(question) for p in pats)]
    return {FEATURES[n][0]: FEATURES[n][1] for n in found}


if __name__ == "__main__":
    for q in ["איפה אפשר לטייל בלי לשלם על כניסה?", "איזה מסלול עם מים מתאים לכיסא גלגלים?",
              "איפה אפשר ללכת בתוך המים בקיץ?", "האם נחל דישון מתאים לילדים, ומתי כדאי ללכת?",
              "איפה אפשר לראות עגורים?", "מסלול מעגלי וקל לעגלה"]:
        print(q, "->", extract_filters(q))
